import puppeteer from 'puppeteer-core';
import { pathToFileURL } from 'node:url';
import { join, resolve } from 'node:path';
import { mkdir } from 'node:fs/promises';
const directory = process.argv[2];
if (!directory) throw new Error('Usage: node scripts/verify-visual-report.mjs <prepared-demo-directory>');
const browser = await puppeteer.launch({ executablePath: process.env.GEO_CHROME || '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome', headless: true });
try {
  const page = await browser.newPage();
  const errors = [];
  page.on('pageerror', e => errors.push(e.message));
  await mkdir(join(directory, 'screenshots'), { recursive: true });
  for (const [name, width, height] of [['desktop', 1440, 1100], ['mobile', 390, 844]]) {
    await page.setViewport({ width, height });
    await page.goto(pathToFileURL(resolve(directory, 'report.html')).href);
    await page.waitForSelector('meter');
    const overflow = await page.evaluate(() => document.documentElement.scrollWidth > innerWidth);
    if (overflow) throw new Error(`${name} overflow`);
    if (await page.$$eval('meter', nodes => nodes.some(n => n.getBoundingClientRect().width < n.parentElement.getBoundingClientRect().width * .9))) throw new Error('Readiness bars lost their full-width scale');
    if (await page.$$eval('meter', nodes => nodes.length) !== 5) throw new Error('Missing original score dimensions');
    await page.screenshot({ path: join(directory, 'screenshots', `${name}.png`), fullPage: true });
    await page.click('details[data-dimension="structure"] summary');
    if (await page.$$eval('[data-rule-drilldown="structure"] tbody tr', nodes => nodes.length) !== 12) throw new Error('Missing per-page structure rules');
    if (await page.evaluate(() => document.documentElement.scrollWidth > innerWidth)) throw new Error('Open rule details overflow the document');
    const ruleScroll = await page.$$eval('[data-rule-drilldown="structure"] .table-wrap', nodes => nodes.map(n => {
      const needsScroll = n.scrollWidth > n.clientWidth;
      n.scrollLeft = n.scrollWidth;
      const result = { overflowX: getComputedStyle(n).overflowX, needsScroll, canScroll: n.scrollLeft > 0, clientWidth: n.clientWidth, scrollWidth: n.scrollWidth };
      n.scrollLeft = 0;
      return result;
    }));
    if (ruleScroll.some(n => n.needsScroll && (!n.canScroll || !['auto', 'scroll'].includes(n.overflowX)))) throw new Error('Rule diagnostic columns cannot be reached');
    console.log(name, 'rule table scrolling', JSON.stringify(ruleScroll));
    await page.screenshot({ path: join(directory, 'screenshots', `${name}-rules.png`), fullPage: true });
    await page.click('details[data-dimension="structure"] summary');
    await page.click('[data-score-bin="0-39"]');
    const visibleBands = await page.$$eval('#page-rows tr', nodes => nodes.filter(n => !n.hidden).map(n => n.dataset.scoreBand));
    if (visibleBands.length !== 1 || visibleBands[0] !== '0-39') throw new Error('Score chart page filter failed');
    await page.click('#clear-page-filter');
    if (await page.$$eval('#page-rows tr', nodes => nodes.filter(n => !n.hidden).length) !== 3) throw new Error('Clear score filter failed');
    await page.type('#page-search', 'no-such-page-123');
    if (!await page.$eval('#no-pages', n => !n.hidden)) throw new Error('Page search empty state failed');
    await page.click('[data-view="overview"]');
    await page.click('[data-severity-filter="critical"]');
    if (await page.$eval('#severity', n => n.value) !== 'critical') throw new Error('Severity chart drilldown failed');
    if (!await page.$eval('#severity', n => n.parentElement.textContent.includes('Scoring severity'))) throw new Error('Unclear filter scope');
    await page.select('#severity', 'critical');
    const wrongVisible = await page.$$eval('#findings details', nodes => nodes.some(n => !n.hidden && n.dataset.severity !== 'critical'));
    if (wrongVisible) throw new Error('Severity filter failed');
    await page.select('#severity', 'all');
    await page.click('#findings details summary');
    if (!await page.$eval('#findings details', n => n.open)) throw new Error('Evidence disclosure failed');
    await page.screenshot({ path: join(directory, 'screenshots', `${name}-evidence.png`), fullPage: true });
    await page.click('[data-view="overview"]');
    await page.click('[data-site-metric="missing-canonicals"]');
    if (!await page.$eval('#site-findings-panel', n => !n.hidden)) throw new Error('Site drilldown panel hidden');
    if (await page.$$eval('[data-site-finding-for="missing-canonicals"] li', nodes => nodes.length) !== 3) throw new Error('Site drilldown targets missing');
    await page.click('#clear-site-findings');
  }
  await page.setViewport({ width: 1440, height: 1100 });
  await page.goto(pathToFileURL(resolve(directory, 'report-after.html')).href);
  if (!await page.$eval('body', n => n.textContent.includes('Before and current'))) throw new Error('Missing comparison chart');
  if (await page.$$eval('details[data-dimension]', nodes => nodes.some(n => Math.abs(n.querySelector('meter').getBoundingClientRect().width - n.querySelector('.baseline-track').getBoundingClientRect().width) > 2))) throw new Error('Baseline/current bars use different physical scales');
  await page.screenshot({ path: join(directory, 'screenshots', 'desktop-comparison.png'), fullPage: false });
  await page.click('.metric-details summary');
  if (await page.$$eval('.metric-details tbody tr', nodes => nodes.length) !== 19) throw new Error('Missing site metrics');
  await page.screenshot({ path: join(directory, 'screenshots', 'desktop-after.png'), fullPage: true });
  await page.click('[data-view="sources"]');
  if (await page.$$eval('#source-comparisons .source-pair', nodes => nodes.length) !== 3) throw new Error('Missing matched source examples');
  if (await page.$$eval('[data-source-capture]', nodes => nodes.filter(n => n.dataset.sourceCapture === 'response-html').length) !== 6) throw new Error('Missing capture provenance');
  if (await page.$eval('[data-panel="overview"]', n => !n.hidden)) throw new Error('Source tab did not hide overview');
  await page.evaluate(() => window.scrollTo(0, 0));
  await page.screenshot({ path: join(directory, 'screenshots', 'desktop-sources.png'), fullPage: false });
  await page.setViewport({ width: 390, height: 844 });
  if (await page.evaluate(() => document.documentElement.scrollWidth > innerWidth)) throw new Error('Source comparison mobile overflow');
  await page.screenshot({ path: join(directory, 'screenshots', 'mobile-sources.png'), fullPage: false });
  if (errors.length) throw new Error(errors.join('\n'));
  console.log('Desktop/mobile rendering, rule drilldowns, score/severity/site chart interactions, page filters, source provenance, matched sources and nineteen metrics passed.');
} finally { await browser.close(); }
